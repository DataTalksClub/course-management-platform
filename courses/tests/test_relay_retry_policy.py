"""Relay retry policy: WAF rate-limit blocks must retry, not park."""

from django.test import SimpleTestCase

import requests

from course_management.relay.retry_policy import (
    is_permanent_relay_error,
    is_waf_rate_block,
)


def http_error(status_code, body=""):
    response = requests.Response()
    response.status_code = status_code
    response._content = body.encode("utf-8")
    error = requests.HTTPError(f"Relay returned {status_code}")
    error.response = response
    return error


CLOUDFRONT_BLOCK = """<!DOCTYPE HTML>
<HEAD><TITLE>ERROR: The request could not be satisfied</TITLE></HEAD>
<BODY><H1>403 ERROR</H1><H2>Request blocked.</H2>
<HR><ADDRESS>Generated by cloudfront (CloudFront)</ADDRESS>
</BODY></HTML>"""


class RelayRetryPolicyTests(SimpleTestCase):
    def test_waf_block_is_transient(self):
        error = http_error(403, CLOUDFRONT_BLOCK)
        self.assertTrue(is_waf_rate_block(error))
        self.assertFalse(is_permanent_relay_error(error))

    def test_plain_403_stays_permanent(self):
        error = http_error(
            403, '{"error": {"code": "forbidden", "fields": {}}}'
        )
        self.assertFalse(is_waf_rate_block(error))
        self.assertTrue(is_permanent_relay_error(error))

    def test_429_and_5xx_and_non_http_are_transient(self):
        self.assertFalse(
            is_permanent_relay_error(http_error(429, "slow down"))
        )
        self.assertFalse(
            is_permanent_relay_error(http_error(500, "boom"))
        )
        self.assertFalse(is_permanent_relay_error(Exception("nope")))
        self.assertFalse(is_waf_rate_block(Exception("nope")))

    def test_404_validation_error_stays_permanent(self):
        error = http_error(
            404, '{"error": {"code": "validation_error"}}'
        )
        self.assertTrue(is_permanent_relay_error(error))
